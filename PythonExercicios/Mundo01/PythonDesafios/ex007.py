# Exercício 007: calcula a média entre duas notas

n1 = float(input('Primeira nota do aluno: '))   # lê a 1ª nota como número decimal
n2 = float(input('Primeira nota do aluno: '))   # lê a 2ª nota como número decimal

print(f'A media entre {n1} e {n2} é igual a {(n1+n2)/2:.1f}')  # f-string calcula a média e mostra com 1 casa decimal
